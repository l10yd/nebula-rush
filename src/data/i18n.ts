const DICTS: Record<Locale, Record<StringKey, string>> = { en: EN, ru: RU };

export type Translate = (key: StringKey, params?: Record<string, string | number>) => string;

export class I18n {
  private locale: Locale = 'en';
  private readonly listeners = new Set<(locale: Locale) => void>();

  get current(): Locale {
    return this.locale;
  }

  setLocale(locale: Locale): void {
    if (locale === this.locale) return;
    this.locale = locale;
    document.documentElement.lang = locale;
    for (const cb of [...this.listeners]) cb(locale);
  }

  onChange(cb: (locale: Locale) => void): () => void {
    this.listeners.add(cb);
    return () => this.listeners.delete(cb);
  }

  t: Translate = (key, params) => {
    const table = DICTS[this.locale] ?? EN;
    let str = table[key] ?? EN[key] ?? (key as string);
    if (params) {
      for (const k in params) {
        str = str.replaceAll(`{${k}}`, String(params[k]));
      }
    }
    return str;
  };
}

export const i18n = new I18n();

/** Convenience for call sites that prefer a function reference. */
export const t: Translate = (key, params) => i18n.t(key, params);
